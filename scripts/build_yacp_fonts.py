"""Generate YACP font assets with the upstream CrossPoint converter."""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

try:
    Import("env")
except NameError:
    ROOT = Path(__file__).resolve().parents[1]
else:
    ROOT = Path(env.subst("$PROJECT_DIR"))
SCRIPT = ROOT / "scripts/build_yacp_fonts.py"
FONT_ROOT = ROOT / "lib/EpdFont/builtinFonts"
OUTPUT = FONT_ROOT / "yacp"
CONVERTER = ROOT / "lib/EpdFont/scripts/fontconvert.py"
STYLES = ("regular", "bold", "italic", "bolditalic")
SIZES = (12, 14, 16, 18, 20)
TABLE_SUFFIX = r"Intervals|Kern(?:Left|Right)(?:Codepoints|ClassIds)|Kern(?:RowOffsets|SparseCols|SparseValues)"
TABLE_DECLARATION = re.compile(
    r"^static const (?P<type>EpdUnicodeInterval|uint16_t|uint8_t|int8_t) "
    rf"(?P<name>\w+(?:{TABLE_SUFFIX}))\[\] = \{{\n(?P<body>.*?)^\}};\n",
    re.MULTILINE | re.DOTALL,
)


def share_font_tables(name, raw_header, shared_tables):
    header = raw_header.decode("utf-8").replace("\r\n", "\n")
    descriptor_start = f"static const EpdFontData {name} = {{\n"
    arrays, separator, descriptor = header.partition(descriptor_start)
    if not separator or '#include "EpdFontData.h"\n' not in arrays:
        raise ValueError(f"{name}: unexpected font converter output")
    aliases = {}

    def intern(match):
        original = match["name"]
        if not original.startswith(name) or original in aliases:
            raise ValueError(f"{name}: unexpected font table {original}")
        key = (match["type"], match["body"])
        shared_name = shared_tables.setdefault(key, f"table{len(shared_tables)}")
        aliases[original] = f"yacp_font_tables::{shared_name}"
        return ""

    arrays = TABLE_DECLARATION.sub(intern, arrays)
    if f"{name}Intervals" not in aliases:
        raise ValueError(f"{name}: missing Unicode interval table")

    def reference(match):
        original = match[0]
        if original not in aliases:
            raise ValueError(f"{name}: missing or repeated font table {original}")
        return aliases.pop(original)

    descriptor = re.sub(rf"\b{re.escape(name)}(?:{TABLE_SUFFIX})\b", reference, descriptor)
    if aliases:
        raise ValueError(f"{name}: unused font tables {', '.join(aliases)}")

    arrays = arrays.replace('#include "EpdFontData.h"', '#include "tables.generated.h"', 1)
    return arrays + descriptor_start + descriptor


def generate():
    manifest_path = ROOT / "scripts/yacp-fonts.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    digest = hashlib.sha256()
    for path in sorted({SCRIPT, CONVERTER, manifest_path} | {
        FONT_ROOT / "source" / name
        for family in manifest.values() for style in family.values() for name in style["fonts"]
    }):
        digest.update(path.read_bytes())
    signature = digest.hexdigest()
    stamp = OUTPUT / "signature.txt"
    expected = [OUTPUT / f"{family}_{size}_{style}.h"
                for family in manifest for size in SIZES for style in STYLES]
    expected += [OUTPUT / name for name in ("families.generated.h", "ids.generated.h", "tables.generated.h")]
    if stamp.exists() and stamp.read_text() == signature and all(p.is_file() for p in expected):
        return
    OUTPUT.mkdir(parents=True, exist_ok=True)
    # An interrupted generation must not leave the previous cache stamp valid.
    stamp.write_text("", encoding="utf-8")

    def convert(item):
        family, size, style = item
        spec = manifest[family][style]
        name = f"{family}_{size}_{style}"
        command = [sys.executable, str(CONVERTER), name, str(size)]
        command += [str(FONT_ROOT / "source" / font) for font in spec["fonts"]]
        for interval in spec["intervals"]:
            command += ["--additional-intervals", interval]
        command += ["--2bit", "--compress", "--pnum", "--zopfli"]
        result = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
        return name, result.stdout

    shared_tables = {}
    face_hashes = {}
    with ThreadPoolExecutor(max_workers=4) as pool:
        for name, raw_header in pool.map(convert, [(f, n, s) for f in manifest for n in SIZES for s in STYLES]):
            # Font IDs must continue to reflect the converter output and stay stable across table sharing.
            face_hashes[name] = int(hashlib.sha256(raw_header).hexdigest(), 16)
            header = share_font_tables(name, raw_header, shared_tables)
            (OUTPUT / f"{name}.h").write_text(header, encoding="utf-8")
            print(f"Generated YACP {name}", flush=True)

    tables = [
        "// Generated by scripts/build_yacp_fonts.py",
        "#pragma once",
        '#include "EpdFontData.h"',
        "",
        "namespace yacp_font_tables {",
    ]
    for (cpp_type, body), name in shared_tables.items():
        tables.append(f"inline constexpr {cpp_type} {name}[] = {{\n{body}}};")
    tables.append("}  // namespace yacp_font_tables")
    (OUTPUT / "tables.generated.h").write_text("\n".join(tables) + "\n", encoding="utf-8")

    families = ["// Generated by scripts/build_yacp_fonts.py", "#pragma once"]
    ids = ["// Generated by scripts/build_yacp_fonts.py", "#pragma once"]
    seen = set()
    for family in manifest:
        for size in SIZES:
            name = f"{family}_{size}"
            font_id = sum(face_hashes[f"{name}_{style}"] for style in STYLES) % (2**32) - 2**31
            if font_id == 0 or font_id in seen:
                raise ValueError("Font ID collision")
            seen.add(font_id)
            ids.append(f"#define YACP_{name.upper()}_FONT_ID ({font_id})")
            condition = "defined(YACP_XLARGE)" if size > 16 else "!defined(YACP_XLARGE)" if size < 16 else "1"
            families.append(f"#if {condition}")
            for style in STYLES:
                families += [f'#include "{name}_{style}.h"', f"static EpdFont {name}_{style}_font(&{name}_{style});"]
            families.append(f"static EpdFontFamily {name}_family({size}, " +
                            ", ".join(f"&{name}_{s}_font" for s in STYLES) + ");")
            families.append("#endif")
    (OUTPUT / "families.generated.h").write_text("\n".join(families)+"\n",encoding="utf-8")
    (OUTPUT / "ids.generated.h").write_text("\n".join(ids)+"\n",encoding="utf-8")
    stamp.write_text(signature)


try:
    Import("env")
except NameError:
    if __name__ == "__main__":
        generate()
else:
    generate()
