"""Identify the one active YACP worktree and attest the inputs of each build."""
import argparse
from contextlib import contextmanager
import csv
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
AUTHORITY = "yacp-source-authority.json"
GENERATED = {
    "lib/I18n/I18nKeys.h",
    "lib/I18n/I18nStrings.cpp",
    "lib/I18n/I18nStrings.h",
    # build_html.py compiles these two standalone SVGs outside the portal.
    "src/components/icons/checkbox_onSvg.generated.h",
    "src/images/logoSvg.generated.h",
}
SKIP_DIRS = {".git", ".cache", "__pycache__", "node_modules", ".pio", "test", "tests", "examples"}


def git(root, *args):
    return subprocess.check_output(["git", "-C", str(root), *args], stderr=subprocess.PIPE).decode().strip()


def identity(root):
    root = root.resolve()
    marker = root / ".yacp-source.json"
    if not marker.is_file():
        raise ValueError("This is a retired/reference tree, not the canonical CrossPoint-based YACP project")
    policy = json.loads(marker.read_text(encoding="utf-8"))
    if policy.get("schema") != 1 or policy.get("product") != "YACP-CrossPoint":
        raise ValueError("Invalid YACP source identity")
    if Path(git(root, "rev-parse", "--show-toplevel")).resolve() != root:
        raise ValueError("YACP must be built from its own Git root")
    subprocess.run(["git", "-C", str(root), "merge-base", "--is-ancestor", policy["upstream_commit"], "HEAD"],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    if git(root / "freeink-sdk", "rev-parse", "HEAD") != policy["sdk_commit"]:
        raise ValueError("SDK checkout differs from the reviewed YACP source policy")
    common = Path(git(root, "rev-parse", "--git-common-dir"))
    if not common.is_absolute():
        common = root / common
    return policy, common.resolve()


def assert_canonical(root=ROOT):
    policy, common = identity(root)
    authority = common / AUTHORITY
    if not authority.is_file():
        raise ValueError("No canonical YACP source registered. Designate it explicitly with check_yacp_source.py --register")
    saved = json.loads(authority.read_text(encoding="utf-8"))
    if saved.get("product") != policy["product"] or Path(saved["root"]).resolve() != root.resolve():
        raise ValueError(f"This worktree is not canonical. Active YACP source: {saved.get('root')}")
    return policy, common


def register(root=ROOT):
    policy, common = identity(root)
    path = common / AUTHORITY
    if path.exists():
        assert_canonical(root)
        return
    with path.open("x", encoding="utf-8") as output:
        json.dump({"schema": 1, "product": policy["product"], "root": str(root.resolve()),
                   "registered_at": int(time.time())}, output, indent=2)


def generated_output(relative):
    # Exclude only outputs regenerated by this project's pre-build scripts.
    # Vendored font headers and all.h are direct compiler inputs, even when
    # their original creation involved a converter outside the current build.
    return (relative in GENERATED
            or relative in {"src/images/YacpLogo120.generated.h", "src/images/YacpLogo.generated.json"}
            or relative.startswith("lib/EpdFont/builtinFonts/yacp/")
            or (relative.startswith("src/network/html/") and relative.endswith(".generated.h")))


def source_manifest(root=ROOT):
    """Hash authored build inputs, including dirty SDK code and ignored font sources."""
    paths = set()
    for directory in ("src", "lib", "include", "scripts", "assets", "freeink-sdk"):
        start = root / directory
        if not start.exists():
            continue
        for folder, dirs, names in os.walk(start, followlinks=False):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not Path(folder, d).is_symlink()]
            for name in names:
                path = Path(folder, name)
                relative = path.relative_to(root).as_posix()
                if generated_output(relative) or name == ".git":
                    continue
                if relative.startswith("freeink-sdk/libs/assets/Icons/lucide/"):
                    continue
                if path.suffix.lower() == ".pyc":
                    continue
                paths.add(relative)
    paths.update(p.name for p in root.glob("platformio*.ini"))
    paths.update({".yacp-source.json", ".gitmodules", "partitions.csv"})
    rows = []
    for name in sorted(paths):
        file = root / name
        if not file.is_file():
            continue
        data = file.read_bytes()
        if name == "platformio.ini":
            data = re.sub(rb"(?m)^crossink_version\s*=.*$", b"crossink_version = BUILD_VERSION", data)
        rows.append({"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
    encoded = json.dumps(rows, sort_keys=True, separators=(",", ":")).encode()
    return {"sha256": hashlib.sha256(encoded).hexdigest(), "files": rows,
            "root": str(root.resolve()), "git_head": git(root, "rev-parse", "HEAD"),
            "branch": git(root, "branch", "--show-current"),
            "sdk_head": git(root / "freeink-sdk", "rev-parse", "HEAD"),
            "dirty": bool(git(root, "status", "--porcelain"))}


@contextmanager
def build_lock(root=ROOT):
    _, common = assert_canonical(root)
    # Retain the lock file. Releasing the OS lock needs no filesystem deletion.
    with (common / "yacp-build.lock").open("a+b") as file:
        if file.tell() == 0:
            file.write(b"0")
            file.flush()
        file.seek(0)
        try:
            if os.name == "nt":
                import msvcrt
                msvcrt.locking(file.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(file, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise ValueError("Another canonical YACP build is already running") from exc
        try:
            yield
        finally:
            file.seek(0)
            if os.name == "nt":
                msvcrt.locking(file.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(file, fcntl.LOCK_UN)


def consume_ticket(root, environment):
    value = os.environ.get("YACP_BUILD_TICKET")
    if not value:
        raise ValueError("Use python scripts/build_yacp.py ENVIRONMENT: direct compilation has no reserved YACP version/provenance")
    ticket_path = Path(value)
    ticket = json.loads(ticket_path.read_text(encoding="utf-8"))
    session = os.environ.get("YACP_BUILD_SESSION")
    if not ticket.get("lease_active") or not session or session != ticket.get("session_id"):
        raise ValueError("Build ticket is inactive/already compiled or belongs to another build session")
    if not ticket_owner_alive(ticket):
        raise ValueError("The build ticket's owning wrapper is no longer running")
    policy = json.loads((root / ".yacp-source.json").read_text(encoding="utf-8"))
    if ticket.get("product") != policy["product"] or ticket.get("environment") != environment:
        raise ValueError("Build ticket does not match this YACP product/profile")
    simulator = environment.startswith("simulator")
    if not simulator and environment not in policy["hardware"]:
        raise ValueError("This hardware profile is outside the unified YACP project")
    execution_root = ticket.get("execution_root") if simulator else ticket.get("source_root")
    if Path(execution_root).resolve() != root.resolve():
        raise ValueError("Build ticket belongs to another source tree or mirror")
    if not simulator:
        assert_canonical(root)
        if source_manifest(root)["sha256"] != ticket["source_sha256"]:
            raise ValueError("Firmware inputs changed after the build version was reserved")
    else:
        actual = {}
        for path in (root / "src").rglob("*"):
            name = path.relative_to(root).as_posix()
            if path.is_file() and not generated_output(name):
                actual[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != ticket.get("mirror_src"):
            raise ValueError("Simulator mirror contains stale/different sources; use a fresh mirror without deleting references")
    version = re.search(r"(?m)^crossink_version\s*=\s*(\S+)", (root / "platformio.ini").read_text(encoding="utf-8"))
    if not version or version[1] != ticket.get("version"):
        raise ValueError("Build ticket has an old/already compiled version")
    ticket["consumed"] = True
    ticket["guard_visits"] = ticket.get("guard_visits", 0) + 1
    ticket["compiled_from"] = str(root.resolve())
    ticket_path.write_text(json.dumps(ticket, indent=2), encoding="utf-8")
    return ticket_path, ticket


def ticket_owner_alive(ticket):
    pid = ticket.get("owner_pid", 0)
    if not isinstance(pid, int) or pid <= 0:
        return False
    if ticket.get("owner_os") == os.name:
        return owner_alive(pid)
    # A Windows wrapper owns the WSL build. Check the PID through WSL interop
    # rather than treating a differing host OS as a live owner.
    if (ticket.get("owner_os") != "nt" or os.name != "posix" or
            not ticket.get("wsl_distro") or os.environ.get("WSL_DISTRO_NAME") != ticket["wsl_distro"]):
        return False
    tasklist = shutil.which("tasklist.exe")
    if not tasklist:
        return False
    try:
        result = subprocess.run([tasklist, "/FI", f"PID eq {pid}", "/FO", "CSV", "/NH"],
                                capture_output=True, encoding="utf-8", errors="replace", timeout=5)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0 and any(len(row) >= 2 and row[1] == str(pid)
                                         for row in csv.reader(result.stdout.splitlines()))


def owner_alive(pid):
    """Read process state without signalling a Windows process."""
    if not isinstance(pid, int) or pid <= 0:
        return False
    if os.name == "nt":
        import ctypes
        from ctypes import wintypes
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        kernel.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
        kernel.OpenProcess.restype = wintypes.HANDLE
        kernel.GetExitCodeProcess.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
        kernel.CloseHandle.argtypes = [wintypes.HANDLE]
        handle = kernel.OpenProcess(0x1000, False, pid)
        if not handle:
            return False
        try:
            code = wintypes.DWORD()
            return bool(kernel.GetExitCodeProcess(handle, ctypes.byref(code))) and code.value == 259
        finally:
            kernel.CloseHandle(handle)
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--register", action="store_true")
    args = parser.parse_args()
    if args.register:
        register()
    policy, _ = assert_canonical()
    print(json.dumps({"canonical": str(ROOT), "product": policy["product"]}))
